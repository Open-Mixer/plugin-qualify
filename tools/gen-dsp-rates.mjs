/*
 * gen-dsp-rates.mjs — `src/dsp-rates.generated.ts`, omx-dsp's ORACLE_FLOOR_RATES and RT_HARD_TARGET as plain data.
 *
 * Both are omx-dsp's declarations (data/primitives/rates.json there, shipped by omx-dsp-contract as
 * `<contractdir>/<schema major>/omx-dsp/primitives/rates.json`). src/qualify-declarations.ts reaches a public subpath that
 * must bundle for a browser, so it cannot read the file: it imports this generated module instead, committed and checked
 * identical, as src/hosting-codes.generated.ts is.
 *
 * The data is looked for in the directories of OMX_CONTRACT_PATH (a ':' list), then the installed contract directory.
 *
 *   node tools/gen-dsp-rates.mjs --check   # exit 1 if the committed file is stale, 2 if omx-dsp's data is absent
 *   node tools/gen-dsp-rates.mjs --write   # (re)write the committed file; the data is required
 *   node tools/gen-dsp-rates.mjs --build   # --write when the data is found, else keep the committed file
 *   node tools/gen-dsp-rates.mjs --check-if-present   # --check where the data is found, else say so and pass (the container job runs --check)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '@openmixer/omx-contract/entry';

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(PKG, 'src/dsp-rates.generated.ts');
const SCHEMA_MAJOR = '3';
const INSTALLED_CONTRACT_DIR = '/usr/share/omx-contract/contract.d';
const RATES_FILE = join(SCHEMA_MAJOR, 'omx-dsp', 'primitives', 'rates.json');

/** Where omx-dsp's rates file is looked for, in order. */
export function ratesFileCandidates(env = process.env) {
  return [...(env.OMX_CONTRACT_PATH ?? '').split(':').filter((d) => d !== ''), INSTALLED_CONTRACT_DIR].map((d) => join(d, RATES_FILE));
}

/** The first candidate that exists, or `undefined`. */
export function findRatesFile(env = process.env) {
  return ratesFileCandidates(env).find((p) => existsSync(p));
}

/** The generated module's text for omx-dsp's rates document `doc`; throws naming what is missing. */
export function dspRatesFile(doc) {
  const floor = doc.ORACLE_FLOOR_RATES?.values;
  const quantum = doc.RT_HARD_TARGET?.value?.quantum;
  if (!Array.isArray(floor) || floor.length === 0 || !floor.every((r) => Number.isInteger(r) && r > 0)) throw new Error('ORACLE_FLOOR_RATES has no list of rates');
  if (!Number.isInteger(quantum) || quantum <= 0) throw new Error('RT_HARD_TARGET has no quantum');
  return (
    `// SPDX-License-Identifier: GPL-3.0-or-later\n` +
    `// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>\n` +
    `//\n` +
    `// GENERATED by tools/gen-dsp-rates.mjs from omx-dsp's data/primitives/rates.json — do not hand-edit.\n` +
    `//\n` +
    `// Regenerate: node tools/gen-dsp-rates.mjs --write\n` +
    `// Verify:     node tools/gen-dsp-rates.mjs --check\n` +
    `\n` +
    `/** omx-dsp's ORACLE_FLOOR_RATES: the rates every kernel oracle runs at (Hz). */\n` +
    `export const ORACLE_FLOOR_RATES: readonly number[] = Object.freeze([${floor.join(', ')}]);\n` +
    `\n` +
    `/** omx-dsp's RT_HARD_TARGET: the real-time target's quantum, in frames. */\n` +
    `export const RT_HARD_TARGET = Object.freeze({ quantum: ${quantum} } as const);\n`
  );
}

function main() {
  const mode = process.argv[2];
  if (!['--check', '--check-if-present', '--write', '--build'].includes(mode)) {
    console.error('usage: node tools/gen-dsp-rates.mjs --check|--check-if-present|--write|--build');
    process.exit(2);
  }
  const file = findRatesFile();
  if (file === undefined) {
    if (mode === '--build' || mode === '--check-if-present') {
      console.log(`gen-dsp-rates: omx-dsp's data not found, ${mode === '--build' ? `keeping the committed ${OUT}` : 'not checked here'}`);
      return;
    }
    console.error(`gen-dsp-rates: omx-dsp's rates file was not found in any of: ${ratesFileCandidates().join(', ')}. Install omx-dsp-contract or set OMX_CONTRACT_PATH.`);
    process.exit(2);
  }
  const content = dspRatesFile(JSON.parse(readFileSync(file, 'utf8')));
  let onDisk;
  try {
    onDisk = readFileSync(OUT, 'utf8');
  } catch {
    onDisk = undefined;
  }
  if (mode === '--check' || mode === '--check-if-present') {
    if (onDisk !== content) {
      console.error(`gen-dsp-rates: ${OUT} is stale against ${file} — run with --write`);
      process.exit(1);
    }
    console.log('gen-dsp-rates: up to date');
    return;
  }
  if (onDisk !== content) writeFileSync(OUT, content);
  console.log(`gen-dsp-rates: ${onDisk === content ? 'up to date' : 'wrote'} ${OUT} from ${file}`);
}

if (isMain(import.meta.url)) main();
