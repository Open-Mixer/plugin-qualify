/**
 * The qualification domain (contract.d/qualification/) follows the rule of data at run time: its items are named
 * QUALIFICATION_*, it states its JSON Schema dialect, and nothing renders it into TypeScript, Python or any other source.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";

const PKG = join(dirname(fileURLToPath(import.meta.url)), "..");
const CONTRACT_DIR = join(PKG, "contract.d");
const DOC = join(CONTRACT_DIR, "qualification", "qualification.json");
const doc = JSON.parse(readFileSync(DOC, "utf8")) as {
  $schema?: string;
  components: { schemas: Record<string, { oneOf: { const: string }[] }> };
};

describe("the qualification domain document", () => {
  it("every item starts with QUALIFICATION_", () => {
    const names = Object.keys(doc.components.schemas);
    expect(names.length).toBeGreaterThan(0);
    for (const name of names) expect(name.startsWith("QUALIFICATION_"), name).toBe(true);
  });
  it("every catalog key starts with an item's name", () => {
    const dir = join(CONTRACT_DIR, "qualification", "catalogs");
    for (const file of readdirSync(dir)) {
      const keys = Object.keys((JSON.parse(readFileSync(join(dir, file), "utf8")) as { messages: Record<string, string> }).messages);
      for (const key of keys) expect(key.startsWith("QUALIFICATION_"), `${file}: ${key}`).toBe(true);
    }
  });
  it("states $schema as JSON Schema 2020-12", () => {
    expect(doc.$schema).toBe("https://json-schema.org/draft/2020-12/schema");
  });
});

describe("nothing renders the domain", () => {
  const tracked = execFileSync("git", ["-C", PKG, "ls-files"], { encoding: "utf8" }).split("\n").filter((f) => f !== "");
  const isCopy = (file: string): boolean => /\.(ts|js|mjs|cjs|d\.ts|py|h)$/.test(file) && !file.endsWith(".test.ts");
  it("no committed file is a render of the domain", () => {
    const found = tracked.filter((file) => {
      if (!isCopy(file)) return false;
      if (/qualification[-_]vocabulary/.test(file)) return true;
      const text = readFileSync(join(PKG, file), "utf8");
      return /GENERATED by `omx-contract render[^`]*--package qualification/.test(text) || /Produced by `omx-contract render[^`]*qualification/.test(text);
    });
    expect(found).toEqual([]);
  });
  it("no source imports a render of the domain, and no script renders it", () => {
    const users = tracked.filter((f) => isCopy(f) && /qualification[-_]vocabulary|gen-qualification-words/.test(readFileSync(join(PKG, f), "utf8")));
    expect(users).toEqual([]);
  });
});
